/**
 * `npm run sync:shared` copies from the frontend:
 *  - its pure rule files into src/shared/, so the /demo/* endpoints validate and compute exactly
 *    what the frontend's forms check;
 *  - its demo data (frontend/src/mocks/data) into src/db/seed-data/, which `npm run db:seed` loads.
 *
 * These files have no dependencies beyond each other, and the frontend already runs them in three
 * places (its forms, its in-browser mock API and its dev-server plugin). Copying them keeps the
 * backend's build self-contained (rootDir stays src/) while the rules cannot drift: change the
 * frontend file, run this, commit both. Never edit the copies by hand.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const backend = join(dirname(fileURLToPath(import.meta.url)), '..')
const from = join(backend, '..', 'frontend', 'src', 'shared')
const to = join(backend, 'src', 'shared')

const DEMO_DATA = ['companies.json', 'posts.json', 'users.json', 'comments.json']

const FILES = [
  'config/formOptions.ts',
  'types/common.ts',
  'types/companySubmission.ts',
  'types/demoSearch.ts',
  'utils/demoPosts.ts',
  'utils/demoReports.ts',
  'utils/moderation.ts',
  'utils/newCompany.ts',
  'utils/tags.ts',
  'utils/text.ts',
]

const HEADER =
  '// GENERATED by `npm run sync:shared` from frontend/src/shared. Do not edit: change the\n' +
  '// frontend file and run the script again.\n'

for (const file of FILES) {
  const source = readFileSync(join(from, file), 'utf8')
  // Node resolves ES modules by their emitted name: './x' and './x.ts' both become './x.js'.
  const rewritten = source.replace(
    /(from\s+['"])(\.{1,2}\/[^'"]+?)(\.ts)?(['"])/g,
    (_match, start, path, _ext, end) => `${start}${path}.js${end}`,
  )
  const target = join(to, file)
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, HEADER + rewritten)
  console.log(`synced ${file}`)
}

const dataFrom = join(backend, '..', 'frontend', 'src', 'mocks', 'data')
const dataTo = join(backend, 'src', 'db', 'seed-data')
for (const file of DEMO_DATA) {
  writeFileSync(join(dataTo, file), readFileSync(join(dataFrom, file)))
  console.log(`synced seed-data/${file}`)
}
