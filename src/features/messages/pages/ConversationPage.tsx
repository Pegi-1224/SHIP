import { useEffect, useRef, useState } from 'react';
import { Link, useParams } from 'react-router-dom';
import { Alert, Anchor, Button, Group, Paper, Stack, Text, Textarea } from '@mantine/core';
import { ArrowLeft, FlaskConical, RotateCcw, Send } from 'lucide-react';
import { env } from '@/shared/config/env';
import { paths } from '@/shared/config/paths';
import { AnonymousAvatar, EmptyState, ErrorState, LoadingState } from '@/shared/ui';
import { getErrorMessage } from '@/shared/api';
import { formatRelativeTime } from '@/shared/utils/format';
import { createClientId } from '@/shared/utils/text';
import { useConversation, useSendMessage } from '../hooks/useMessages';
import styles from './Messages.module.css';

/**
 * One conversation thread (spec 3.7, 6.7).
 *
 * RETRY WITHOUT DUPLICATES
 *   A `clientMessageId` is generated once when the user presses Send and is
 *   kept for every retry of that same message. The server uses it as an
 *   idempotency key, so a send that actually succeeded but looked like a
 *   failure cannot be stored twice. The id is only cleared after a confirmed
 *   success, when the composer is emptied.
 *
 * The MVP does not support editing or retracting a sent message, so no such
 * control is offered.
 */
export function ConversationPage() {
  const { conversationId } = useParams<{ conversationId: string }>();
  const thread = useConversation(conversationId);
  const send = useSendMessage(conversationId ?? '');

  const [draft, setDraft] = useState('');
  // Held across retries so the server can recognise the repeat.
  const pendingClientId = useRef<string | null>(null);
  const endOfThread = useRef<HTMLDivElement>(null);

  const messageCount = thread.data?.messages.length ?? 0;
  useEffect(() => {
    endOfThread.current?.scrollIntoView({ block: 'end' });
  }, [messageCount]);

  const submit = () => {
    const body = draft.trim();
    if (!body || send.isPending) return;

    pendingClientId.current ??= createClientId('msg');

    send.mutate(
      { body, clientMessageId: pendingClientId.current },
      {
        onSuccess: () => {
          // Only now is it safe to forget the id and clear the box.
          pendingClientId.current = null;
          setDraft('');
        },
        // On failure the draft and the id are both kept, so Retry resends the
        // same message rather than composing a new one.
      },
    );
  };

  if (thread.isPending) return <LoadingState label="Loading conversation…" />;

  if (thread.isError) {
    return (
      <Stack gap="md">
        <BackLink />
        <ErrorState
          error={thread.error}
          title="We could not load this conversation"
          onRetry={() => void thread.refetch()}
          isRetrying={thread.isFetching}
        />
      </Stack>
    );
  }

  const { conversation, messages } = thread.data;

  return (
    <Stack gap="md" className={styles.thread}>
      <BackLink />

      <Group gap="sm">
        <AnonymousAvatar identity={conversation.peer} />
        <div>
          <Text fw={600}>{conversation.peer.label}</Text>
          <Text size="xs" c="dimmed">
            Both sides of this conversation are anonymous.
          </Text>
        </div>
      </Group>

      {env.enableMocks ? (
        <Alert
          color="ship"
          variant="light"
          icon={<FlaskConical size={16} aria-hidden="true" />}
          role="note"
        >
          <Text size="sm">
            There is nobody on the other end. Replies in this thread are generated by the mock API a
            few seconds after you send something.
          </Text>
        </Alert>
      ) : null}

      <Paper withBorder p="md" className={styles.messageList}>
        {messages.length === 0 ? (
          <EmptyState
            title="Say hello"
            description="No messages yet. Write the first one below."
          />
        ) : (
          <Stack gap="sm">
            {messages.map((message) => (
              <div
                key={message.id}
                className={
                  message.direction === 'outgoing' ? styles.bubbleOutgoing : styles.bubbleIncoming
                }
              >
                <Text size="sm" className={styles.bubbleText}>
                  {message.body}
                </Text>
                <Text size="xs" className={styles.bubbleTime}>
                  <span className="ship-visually-hidden">
                    {message.direction === 'outgoing' ? 'You wrote: ' : 'They wrote: '}
                  </span>
                  {formatRelativeTime(message.createdAt)}
                </Text>
              </div>
            ))}
            <div ref={endOfThread} />
          </Stack>
        )}
      </Paper>

      {send.isError ? (
        <Alert color="red" variant="light" role="alert" title="Your message was not sent">
          <Text size="sm">{getErrorMessage(send.error)}</Text>
          <Text size="xs" c="dimmed" mt={4}>
            Your text is still in the box. Retrying resends the same message - it cannot be
            delivered twice.
          </Text>
          <Button
            size="xs"
            variant="light"
            color="red"
            mt="sm"
            onClick={submit}
            loading={send.isPending}
            leftSection={<RotateCcw size={14} aria-hidden="true" />}
          >
            Retry
          </Button>
        </Alert>
      ) : null}

      <form
        onSubmit={(event) => {
          event.preventDefault();
          submit();
        }}
      >
        <Group align="flex-end" gap="sm" wrap="nowrap">
          <Textarea
            label="Message"
            labelProps={{ className: 'ship-visually-hidden' }}
            placeholder="Write a message"
            value={draft}
            onChange={(event) => setDraft(event.currentTarget.value)}
            autosize
            minRows={1}
            maxRows={5}
            className={styles.composer}
            onKeyDown={(event) => {
              if (event.key === 'Enter' && !event.shiftKey) {
                event.preventDefault();
                submit();
              }
            }}
          />
          <Button
            type="submit"
            loading={send.isPending}
            disabled={draft.trim().length === 0 || send.isPending}
            leftSection={<Send size={16} aria-hidden="true" />}
          >
            Send
          </Button>
        </Group>
        <Text size="xs" c="dimmed" mt={4}>
          Enter sends, Shift+Enter adds a line. Sent messages cannot be edited or deleted in this
          version.
        </Text>
      </form>
    </Stack>
  );
}

function BackLink() {
  return (
    <Anchor component={Link} to={paths.messages()} size="sm">
      <Group gap={4} component="span">
        <ArrowLeft size={14} aria-hidden="true" />
        All messages
      </Group>
    </Anchor>
  );
}
